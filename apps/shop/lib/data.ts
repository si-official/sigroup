export function getProduct(slug: string) {
  return products.find(p => p.slug === slug)
}

export function getSeller(id: string) {
  return sellers.find(s => s.id === id)
}

export function getProductsWithSellers(): Product[] {
  return products.map(p => ({ ...p, seller: sellers.find(s => s.id === p.sellerId) }))
}

export function getSellerProducts(sellerId: string): Product[] {
  return products.filter(p => p.sellerId === sellerId).map(p => ({ ...p, seller: sellers.find(s => s.id === p.sellerId) }))
}

export function getRelatedProducts(product: Product): Product[] {
  return products.filter(p => p.id !== product.id && (p.category === product.category || p.sellerId === product.sellerId)).slice(0, 4).map(p => ({ ...p, seller: sellers.find(s => s.id === p.sellerId) }))
}
